//! Initial schema. See docs/data-model/index.html for the reasoning behind each table.
//!
//! Written as plain SQL: the project only targets Postgres, and SQL is the easiest form to review.
//! Migrations only run forward; for real data, restore a backup instead of migrating down.

use sea_orm_migration::prelude::*;

pub struct Migration;

impl MigrationName for Migration {
    fn name(&self) -> &str {
        "m20261122_000001_init"
    }
}

const UP: &str = r#"
CREATE TYPE link_kind AS ENUM ('transfer', 'reimbursement');
CREATE TYPE category_kind AS ENUM ('expense', 'income');

CREATE TABLE accounts (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL UNIQUE,
    created_at  timestamptz NOT NULL DEFAULT now()
);

-- One file upload. The whole import runs in one DB transaction, so there is no partial state.
CREATE TABLE import_batches (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id   bigint NOT NULL REFERENCES accounts (id) ON DELETE RESTRICT,
    source       text NOT NULL,              -- parser id, e.g. 'ing_csv'
    file_name    text,
    file_sha256  text NOT NULL UNIQUE,       -- same file again -> no-op
    inserted     integer NOT NULL DEFAULT 0,
    duplicates   integer NOT NULL DEFAULT 0,
    imported_at  timestamptz NOT NULL DEFAULT now()
);

-- Transactions that belong together. Members point here through transactions.link_group_id.
CREATE TABLE link_groups (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind        link_kind NOT NULL,
    title       text,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE categories (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id  bigint REFERENCES categories (id) ON DELETE RESTRICT,
    name       text NOT NULL,
    kind       category_kind NOT NULL,
    CONSTRAINT categories_parent_id_name_key UNIQUE NULLS NOT DISTINCT (parent_id, name)
);

-- One line from a bank or card statement. amount_cents is signed from the account's view.
CREATE TABLE transactions (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id         bigint NOT NULL REFERENCES accounts (id) ON DELETE RESTRICT,
    import_batch_id    bigint NOT NULL REFERENCES import_batches (id) ON DELETE CASCADE,
    import_key         text NOT NULL,        -- '{parser}:v{n}:{key}', built by the parser
    booked_on          date NOT NULL,
    amount_cents       bigint NOT NULL,
    counterparty_name  text,
    counterparty_iban  text,
    description        text NOT NULL,
    link_group_id      bigint REFERENCES link_groups (id) ON DELETE SET NULL,
    notes              text,
    raw                jsonb NOT NULL,
    created_at         timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT transactions_account_id_import_key_key UNIQUE (account_id, import_key)
);
CREATE INDEX transactions_account_id_booked_on_idx ON transactions (account_id, booked_on);
CREATE INDEX transactions_import_batch_id_idx ON transactions (import_batch_id);
CREATE INDEX transactions_link_group_id_idx ON transactions (link_group_id);

-- The part of a transaction that belongs to one category. No splits = uncategorized.
-- The backend guarantees that a transaction's splits add up to its amount_cents.
CREATE TABLE transaction_splits (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id  bigint NOT NULL REFERENCES transactions (id) ON DELETE CASCADE,
    category_id     bigint NOT NULL REFERENCES categories (id) ON DELETE RESTRICT,
    amount_cents    bigint NOT NULL CHECK (amount_cents <> 0),
    CONSTRAINT transaction_splits_transaction_id_category_id_key UNIQUE (transaction_id, category_id)
);
CREATE INDEX transaction_splits_category_id_idx ON transaction_splits (category_id);
"#;

#[async_trait::async_trait]
impl MigrationTrait for Migration {
    async fn up(&self, manager: &SchemaManager) -> Result<(), DbErr> {
        manager.get_connection().execute_unprepared(UP).await?;
        Ok(())
    }
}
